#!/usr/bin/env node
/**
 * Render the architecture diagrams from the contract and Fallow's graph.
 *
 * `docs/architecture/roles.mmd` is the canonical diagram: every role in
 * `.fallowrc.jsonc` and every direction its rules allow. Each result gets
 * `<root>/architecture.mmd`: the roles its files hold and the role edges its
 * imports resolve to. Both use one set of conventions (node ids, labels,
 * subgraphs, sort order, dashed type-only edges), so two diagrams differ in
 * text only where their structure differs.
 *
 * `node tooling/architecture/diagram.mjs` (`pnpm arch:diagram`) writes every
 * diagram, and fails on a diagram at a root that is no result, which it
 * leaves for a person to remove. `--check` writes no diagram and fails on a
 * missing, stale or extra one. `--root <dir>` targets another repository.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readRepository, runCli } from './graph.mjs';

const CONTRACT_DIAGRAM = 'docs/architecture/roles.mmd';
const GENERATOR = 'Generated by tooling/architecture/diagram.mjs (pnpm arch:diagram)';
const KINDS = ['web', 'api', 'ui'];

const nodeId = (role) => role.replace(/-/g, '_');

/** True when the contract allows `from` to reach `to` by a type-only import and no other. */
function isTypeOnly(contract, from, to) {
  const matching = contract.directions.filter((d) => d.from === from && d.to === to);
  return matching.length > 0 && matching.every((d) => d.typeOnly);
}

/** The Mermaid text for `roles` and role-to-role `edges`, with `header` as its first line. */
function renderDiagram(contract, header, roles, edges) {
  const subgraphs = KINDS.flatMap((kind) => {
    const members = contract.roles.filter(
      (role) => roles.has(role) && contract.kindOf(role) === kind,
    );
    return members.length === 0
      ? []
      : [
          `  subgraph kind_${kind}["${kind}"]`,
          ...members.map((role) => `    ${nodeId(role)}["${role}"]`),
          '  end',
        ];
  });
  const edgeLines = [...edges]
    .map(([from, to]) => ({
      key: `${nodeId(from)} ${nodeId(to)}`,
      line: `  ${nodeId(from)} ${isTypeOnly(contract, from, to) ? '-.->' : '-->'} ${nodeId(to)}`,
    }))
    .sort((a, b) => (a.key < b.key ? -1 : 1))
    .map(({ line }) => line);
  return [`%% ${header}. Do not edit.`, 'flowchart LR', ...subgraphs, ...edgeLines, ''].join('\n');
}

/** @param {import('./contract.mjs').Contract} contract */
export function renderContractDiagram(contract) {
  const edges = new Map(contract.directions.map(({ from, to }) => [`${from} ${to}`, [from, to]]));
  return renderDiagram(
    contract,
    `${GENERATOR}: every role and allowed direction in .fallowrc.jsonc`,
    new Set(contract.roles),
    edges.values(),
  );
}

/**
 * @param {import('./contract.mjs').Contract} contract
 * @param {{ id: string, root: string }} result
 * @param {readonly import('./graph.mjs').FileEdge[]} edges
 */
export function renderResultDiagram(contract, result, edges) {
  const roles = new Set();
  const roleEdges = new Map();
  for (const edge of edges.filter(({ from }) => from.startsWith(`${result.root}/`))) {
    const from = contract.roleOf(edge.from);
    const to = contract.roleOf(edge.to);
    for (const role of [from, to].filter(Boolean)) {
      roles.add(role);
    }
    if (from && to && from !== to) {
      roleEdges.set(`${from} ${to}`, [from, to]);
    }
  }
  return renderDiagram(
    contract,
    `${GENERATOR}: result ${result.id} (${result.root}), the role edges of Fallow's import graph`,
    roles,
    roleEdges.values(),
  );
}

/** Each diagram path to its expected text: the canonical diagram, then one per result. */
export function planDiagrams(contract, results, edges) {
  return new Map([
    [CONTRACT_DIAGRAM, renderContractDiagram(contract)],
    ...results.map((result) => [
      `${result.root}/architecture.mmd`,
      renderResultDiagram(contract, result, edges),
    ]),
  ]);
}

/** The paths this generator owns: the canonical diagram and a diagram at any result root. */
const isDiagram = (path) =>
  path === CONTRACT_DIAGRAM || /^(?:apps|showcase\/[^/]+)\/architecture\.mmd$/.test(path);

/**
 * The planned diagrams missing from `files`, those whose text differs, and the
 * diagrams at a root that is no result.
 */
export function diffDiagrams(plan, files, readText) {
  const present = files.filter(isDiagram);
  return {
    missing: [...plan.keys()].filter((path) => !present.includes(path)),
    stale: present.filter((path) => plan.has(path) && readText(path) !== plan.get(path)),
    extra: present.filter((path) => !plan.has(path)).sort(),
  };
}

function main(root) {
  const { contract, edges, files, results } = readRepository(root);
  const plan = planDiagrams(contract, results, edges);
  const diff = diffDiagrams(plan, files, (path) => readFileSync(join(root, path), 'utf8'));
  const extra = diff.extra.map(
    (path) => `extra diagram: ${path}; no result owns it, so remove it.`,
  );
  if (process.argv.includes('--check')) {
    const problems = [
      ...diff.missing.map((path) => `missing diagram: ${path}`),
      ...diff.stale.map((path) => `stale diagram: ${path}`),
      ...extra,
    ];
    if (problems.length > 0) {
      console.error(
        [...problems, 'Run `pnpm arch:diagram` and keep the written diagrams.'].join('\n'),
      );
      return false;
    }
    console.log(`OK: ${plan.size} diagrams match the contract and the import graph.`);
    return true;
  }
  for (const [path, text] of plan) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
    console.log(`Wrote ${path}`);
  }
  if (extra.length > 0) {
    console.error(extra.join('\n'));
  }
  return extra.length === 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  runCli(main);
}
