#!/usr/bin/env node
/**
 * Render the role-level architecture diagram from Fallow's own outputs.
 *
 * `fallow viz --viz-format dot` gives the file-level import graph and
 * `fallow list --boundaries --format json` gives the zones from
 * `.fallowrc.jsonc`. `renderRoleDiagram` maps each file to its role (the
 * zone's logical group, or the zone name), keeps only edges between two
 * different roles, and prints a sorted Mermaid flowchart. Files outside every
 * zone (tests, scripts, configs, e2e) are left out, so the diagram shows the
 * shape the rules file governs and only moves when that shape moves.
 *
 * The CLI (`pnpm arch:diagram`) runs Fallow and writes
 * `docs/architecture/roles.mmd`.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const FALLOW = join(REPOSITORY_ROOT, 'node_modules/.bin/fallow');
const CACHE_DIRECTORY = join(REPOSITORY_ROOT, '.cache/arch');
const DIAGRAM_PATH = join(REPOSITORY_ROOT, 'docs/architecture/roles.mmd');

const HEADER =
  '%% Generated by `pnpm arch:diagram` from .fallowrc.jsonc. Edit the rules file, not this file.';

/** Translate a Fallow zone glob (`**`, `*`, `{a,b}`, literal paths) into an anchored RegExp. */
export function globToRegExp(pattern) {
  let body = '';
  let braceDepth = 0;
  for (let index = 0; index < pattern.length; index += 1) {
    const character = pattern[index];
    if (pattern.startsWith('**', index)) {
      body += '.*';
      index += 1;
    } else if (character === '*') {
      body += '[^/]*';
    } else if (character === '{') {
      braceDepth += 1;
      body += '(?:';
    } else if (character === '}' && braceDepth > 0) {
      braceDepth -= 1;
      body += ')';
    } else if (character === ',' && braceDepth > 0) {
      body += '|';
    } else {
      body += character.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
    }
  }
  return new RegExp(`^${body}$`);
}

/** Build `file -> role` from the boundaries listing; zones match in declared order. */
function createRoleLookup(boundariesJson) {
  const { boundaries } = JSON.parse(boundariesJson);
  const groupOfZone = new Map(
    boundaries.logical_groups.flatMap((group) =>
      group.children.map((child) => [child, group.name]),
    ),
  );
  const matchers = boundaries.zones.flatMap((zone) =>
    zone.patterns.map((pattern) => ({
      regExp: globToRegExp(pattern),
      role: groupOfZone.get(zone.name) ?? zone.name,
    })),
  );
  const roles = [...new Set(matchers.map((matcher) => matcher.role))].sort();
  const roleOf = (file) => matchers.find((matcher) => matcher.regExp.test(file))?.role;
  return { roles, roleOf };
}

const nodeId = (role) => role.replace(/[^A-Za-z0-9]/g, '_');

/**
 * The labelled files and the file-to-file edges of `fallow viz --viz-format dot`
 * output. An empty parse means Fallow's dot format changed; failing here keeps a
 * silently empty diagram out of the repo.
 */
function parseDot(dotText) {
  const labels = new Map(
    [...dotText.matchAll(/^\s*(n\d+) \[label="([^"]+)"/gm)].map(([, id, label]) => [id, label]),
  );
  if (labels.size === 0) {
    throw new Error(
      'fallow-roles: the dot graph has no labelled nodes; check the Fallow output format.',
    );
  }
  const edges = [...dotText.matchAll(/^\s*(n\d+) -> (n\d+);/gm)].map(([, from, to]) => [
    labels.get(from) ?? '',
    labels.get(to) ?? '',
  ]);
  if (edges.length === 0) {
    throw new Error('fallow-roles: the dot graph has no edges; check the Fallow output format.');
  }
  return edges;
}

/**
 * Collapse Fallow's file graph into a Mermaid role diagram.
 *
 * @param {string} dotText output of `fallow viz --viz-format dot`
 * @param {string} boundariesJson output of `fallow list --boundaries --format json`
 * @returns {string} the Mermaid source, ending in a newline
 */
export function renderRoleDiagram(dotText, boundariesJson) {
  const fileEdges = parseDot(dotText);
  const { roles, roleOf } = createRoleLookup(boundariesJson);
  const roleEdges = new Set(
    fileEdges
      .map(([from, to]) => [roleOf(from), roleOf(to)])
      .filter(([fromRole, toRole]) => fromRole && toRole && fromRole !== toRole)
      .map(([fromRole, toRole]) => `  ${nodeId(fromRole)} --> ${nodeId(toRole)}`),
  );

  // Roles with no edge between them mean the zone globs matched no file, which
  // would commit a diagram that shows the roles and none of the contract.
  if (roleEdges.size === 0) {
    throw new Error(
      'fallow-roles: no import crosses two roles; check that the zone patterns match the files.',
    );
  }

  return [
    HEADER,
    'flowchart LR',
    ...roles.map((role) => `  ${nodeId(role)}["${role}"]`),
    ...[...roleEdges].sort(),
    '',
  ].join('\n');
}

function runFallow(args) {
  return execFileSync(FALLOW, args, { cwd: REPOSITORY_ROOT, encoding: 'utf8' });
}

/** The zones from `.fallowrc.jsonc`, as printed by `fallow list --boundaries --format json`. */
export function readFallowBoundaries() {
  return runFallow(['list', '--boundaries', '--format', 'json', '-q']);
}

function runCli() {
  mkdirSync(CACHE_DIRECTORY, { recursive: true });
  const dotPath = join(CACHE_DIRECTORY, 'graph.dot');
  runFallow(['viz', '--no-open', '--viz-format', 'dot', '--out', dotPath, '-q']);
  const boundariesJson = readFallowBoundaries();

  const diagram = renderRoleDiagram(readFileSync(dotPath, 'utf8'), boundariesJson);
  mkdirSync(dirname(DIAGRAM_PATH), { recursive: true });
  writeFileSync(DIAGRAM_PATH, diagram);
  console.log(`Wrote ${DIAGRAM_PATH.slice(REPOSITORY_ROOT.length + 1)}`);
}

// Run the CLI only when invoked directly, not when imported by a test.
if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    runCli();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
